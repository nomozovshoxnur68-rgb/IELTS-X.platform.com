/* Rebuilds assets/js/practice-cards.js: the list of the cards on the four practice pages
 * (part/practice/reading|listening|writing|speaking) so the admin panel (Access) can manage each of them.
 * Run it again after you add or rename a card:  node scripts/build-practice-cards.js */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const app = fs.readFileSync(path.join(ROOT, 'assets/js/app.js'), 'utf8');
function grab(marker) {
  let i = app.indexOf(marker); if (i < 0) throw new Error('not found in app.js: ' + marker);
  i = app.indexOf('[', i); let d = 0, j = i, q = null;
  for (; j < app.length; j++) {
    const c = app[j];
    if (q) { if (c === '\\') { j++; continue; } if (c === q) q = null; continue; }
    if (c === "'" || c === '"' || c === '`') { q = c; continue; }
    if (c === '[') d++; else if (c === ']') { d--; if (d === 0) break; }
  }
  return vm.runInNewContext(app.slice(i, j + 1));
}
const slug = (s) => String(s || '').toLowerCase().trim().replace(/[^a-z0-9_]+/g, '-').replace(/^-+|-+$/g, '');
const base = (h) => slug(String(h).split(/[?#]/)[0].split('/').pop().replace(/\.html$/i, ''));
const reading = grab('const cardData = [{').map((c) => ({ id: base(c.href), title: c.title, href: c.href.replace(/\.html$/i, ''), free: /free/i.test(c.status || c.badge || '') }));
const listening = fs.readFileSync(path.join(ROOT, 'part/practice/listening.html'), 'utf8').split('class="h-full"').slice(1).map((c) => {
  const href = (c.match(/href="(\/sections[^"]+)"/) || [])[1]; const t = (c.match(/<h3[^>]*>\s*([^<]+?)\s*</) || [])[1];
  return href && t ? { id: base(href), title: t, href, free: true } : null;
}).filter(Boolean);
const writing = grab('const writingData = [').map((c) => ({ id: 'w' + c.id, title: c.title, to: '/full-tests/writing/' + slug(c.pack), free: false }));
const speaking = grab('const topicsData = [').map((c) => ({ id: 's' + c.id, title: c.title, to: '/full-tests/speaking/' + slug(c.pack), free: false }));
const out = { reading: { title: 'Reading passages', page: '/part/practice/reading', cards: reading },
  listening: { title: 'Listening sections', page: '/part/practice/listening', cards: listening },
  writing: { title: 'Writing tasks', page: '/part/practice/writing', cards: writing },
  speaking: { title: 'Speaking topics', page: '/part/practice/speaking', cards: speaking } };
fs.writeFileSync(path.join(ROOT, 'assets/js/practice-cards.js'),
  '/* generated by scripts/build-practice-cards.js - do not edit by hand */\nwindow.IELTSX_PRACTICE = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('practice cards:', Object.entries(out).map(([k, v]) => k + ' ' + v.cards.length).join(', '));
